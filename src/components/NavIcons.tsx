/**
 * Sidebar glyphs supplied as raw SVG by design.
 *
 * Each icon keeps its original artwork and viewBox. Inactive items render the
 * supplied white radial gradient; active items switch to `currentColor` so the
 * purple treatment on the active tile can drive them.
 */
type NavIconProps = {
  size?: number
  /** Swap the supplied gradient for `currentColor`. */
  active?: boolean
}

const base = (size: number, viewBox: string) => ({
  width: size,
  height: size,
  viewBox,
  fill: 'none',
  xmlns: 'http://www.w3.org/2000/svg',
  'aria-hidden': true,
  focusable: false,
})

/** White 25% → 75% radial wash used by the supplied artwork. */
function Wash({
  id,
  transform,
}: {
  id: string
  transform: string
}) {
  return (
    <radialGradient
      id={id}
      cx="0"
      cy="0"
      r="1"
      gradientUnits="userSpaceOnUse"
      gradientTransform={transform}
    >
      <stop stopColor="white" stopOpacity="0.25" />
      <stop offset="1" stopColor="white" stopOpacity="0.75" />
    </radialGradient>
  )
}

