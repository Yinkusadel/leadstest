/**
 * Renders the supplied Union Jack for GB senders and falls back to the emoji
 * flag for the others — only the UK artwork was provided.
 */
export function CountryFlag({ emoji, size = 15 }: { emoji: string; size?: number }) {
  if (emoji === '🇬🇧') return <UKFlag size={size} />
  return (
    <span aria-hidden className="leading-none" style={{ fontSize: size }}>
      {emoji}
    </span>
  )
}

